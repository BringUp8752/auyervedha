CREATE TABLE categories(id SERIAL PRIMARY KEY,name TEXT UNIQUE NOT NULL,color TEXT);
CREATE TABLE brands(id SERIAL PRIMARY KEY,name TEXT UNIQUE NOT NULL);
CREATE TABLE products(id SERIAL PRIMARY KEY,name TEXT NOT NULL,category_id INT NOT NULL REFERENCES categories(id),brand_id INT REFERENCES brands(id),price NUMERIC(10,2) NOT NULL,image_url TEXT,stock INT DEFAULT 100,hidden BOOLEAN DEFAULT false);
CREATE TABLE users(id SERIAL PRIMARY KEY,name TEXT,email TEXT UNIQUE NOT NULL,created_at TIMESTAMPTZ DEFAULT now());
CREATE TABLE coupons(code TEXT PRIMARY KEY,percent_off INT NOT NULL CHECK(percent_off BETWEEN 1 AND 100),active BOOLEAN DEFAULT true,expires_at TIMESTAMPTZ);
CREATE TABLE orders(id SERIAL PRIMARY KEY,user_id INT REFERENCES users(id),address TEXT,coupon_code TEXT REFERENCES coupons(code),total NUMERIC(10,2) NOT NULL,status TEXT DEFAULT 'New',created_at TIMESTAMPTZ DEFAULT now());
CREATE TABLE order_items(id SERIAL PRIMARY KEY,order_id INT NOT NULL REFERENCES orders(id),product_id INT NOT NULL REFERENCES products(id),quantity INT NOT NULL,unit_price NUMERIC(10,2) NOT NULL);

